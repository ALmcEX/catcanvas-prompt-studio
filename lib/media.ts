import sharp, { type OverlayOptions } from "sharp";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { parse, type Font } from "opentype.js";

let fontPromise: Promise<Font> | undefined;
function captionFont() {
  return (fontPromise ??= readFile(
    path.join(process.cwd(), "assets/fonts/NotoSans-Latin-Regular.woff"),
  ).then((bytes) =>
    parse(
      bytes.buffer.slice(
        bytes.byteOffset,
        bytes.byteOffset + bytes.byteLength,
      ) as ArrayBuffer,
    ),
  ));
}
export async function normalizeImage(input: Buffer): Promise<Buffer> {
  if (!input.length || input.length > 4194304)
    throw new Error("Upload a PNG, JPEG or WebP image under 4 MB.");
  try {
    const img = sharp(input, { limitInputPixels: 20000000, animated: false });
    const meta = await img.metadata();
    if (
      !["png", "jpeg", "webp"].includes(meta.format ?? "") ||
      (meta.pages ?? 1) > 1
    )
      throw Error();
    return await img
      .rotate()
      .resize({
        width: 1600,
        height: 1600,
        fit: "inside",
        withoutEnlargement: true,
      })
      .png()
      .toBuffer();
  } catch {
    throw new Error("The uploaded file is not a supported image.");
  }
}
export async function mediaSvg(
  name: string,
  output: string,
  hasImage: boolean,
): Promise<string> {
  const font = await captionFont();
  const textPath = (
    text: string,
    x: number,
    y: number,
    size: number,
    color: string,
  ) => {
    const shape = font.getPath(text, x, y, size);
    shape.fill = color;
    return shape.toSVG(2);
  };
  const lines: string[] = [];
  for (const paragraph of [...output].slice(0, 1200).join("").split("\n")) {
    let line = "";
    for (const word of paragraph.split(/\s+/)) {
      if ([...(line + " " + word)].length > 58 && line) {
        lines.push(line);
        line = "";
      }
      if (word.length > 58) {
        if (line) lines.push(line);
        for (let i = 0; i < word.length; i += 58)
          lines.push(word.slice(i, i + 58));
        line = "";
      } else line += (line ? " " : "") + word;
    }
    if (line) lines.push(line);
  }
  const top = hasImage ? 790 : 190;
  const height = Math.max(420, top + Math.min(lines.length, 32) * 38 + 100);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="${height}"><rect width="1200" height="${height}" fill="#f7f3e9"/><rect x="48" y="48" width="42" height="8" rx="4" fill="#e77b4c"/>${textPath("CATCANVAS / PROMPT STUDIO", 108, 63, 20, "#52624f")}${textPath([...name].slice(0, 65).join(""), 48, 125, 30, "#233128")}${lines
    .slice(0, 32)
    .map((line, i) => textPath(line, 48, top + i * 38, 29, "#233128"))
    .join(
      "",
    )}${textPath("Generated by a prompt chain · Full output in run details", 48, height - 35, 16, "#687562")}</svg>`;
}

export async function renderMedia(
  name: string,
  output: string,
  image?: Buffer,
): Promise<Buffer> {
  const svg = Buffer.from(await mediaSvg(name, output, Boolean(image)));
  const height = (await sharp(svg).metadata()).height!;
  const composite: OverlayOptions[] = [{ input: svg, top: 0, left: 0 }];
  if (image)
    composite.push({
      input: await sharp(image)
        .resize(1104, 570, { fit: "contain", background: "#e9e4d9" })
        .png()
        .toBuffer(),
      top: 160,
      left: 48,
    });
  return sharp({
    create: { width: 1200, height, channels: 4, background: "#f7f3e9" },
  })
    .composite(composite)
    .png()
    .toBuffer();
}
