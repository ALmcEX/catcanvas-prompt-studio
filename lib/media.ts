import sharp, { type OverlayOptions } from "sharp";
export async function normalizeImage(input: Buffer): Promise<Buffer> {
  if (!input.length || input.length > 4194304)
    throw new Error("Upload a PNG, JPEG or WebP image under 4 MB.");
  try {
    const img = sharp(input, { limitInputPixels: 20000000, animated: false });
    const meta = await img.metadata();
    if (
      !["png", "jpeg", "webp"].includes(meta.format ?? "") ||
      (meta.pages ?? 1) > 1
    )
      throw Error();
    return await img
      .rotate()
      .resize({
        width: 1600,
        height: 1600,
        fit: "inside",
        withoutEnlargement: true,
      })
      .png()
      .toBuffer();
  } catch {
    throw new Error("The uploaded file is not a supported image.");
  }
}
const xml = (s: string) =>
  s.replace(
    /[&<>"']/g,
    (c) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&apos;",
      })[c]!,
  );
export async function renderMedia(
  name: string,
  output: string,
  image?: Buffer,
): Promise<Buffer> {
  const lines: string[] = [];
  for (const paragraph of [...output].slice(0, 1200).join("").split("\n")) {
    let line = "";
    for (const word of paragraph.split(/\s+/)) {
      if ([...(line + " " + word)].length > 58 && line) {
        lines.push(line);
        line = "";
      }
      if (word.length > 58) {
        if (line) lines.push(line);
        for (let i = 0; i < word.length; i += 58)
          lines.push(word.slice(i, i + 58));
        line = "";
      } else line += (line ? " " : "") + word;
    }
    if (line) lines.push(line);
  }
  const top = image ? 790 : 190;
  const height = Math.max(420, top + Math.min(lines.length, 32) * 38 + 100);
  const svg = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="${height}"><rect width="1200" height="${height}" fill="#f7f3e9"/><rect x="48" y="48" width="42" height="8" rx="4" fill="#e77b4c"/><text x="108" y="63" font-family="sans-serif" font-size="20" fill="#52624f">CATCANVAS / PROMPT STUDIO</text><text x="48" y="125" font-family="sans-serif" font-size="30" font-weight="bold" fill="#233128">${xml([...name].slice(0, 65).join(""))}</text>${lines
      .slice(0, 32)
      .map(
        (line, i) =>
          `<text x="48" y="${top + i * 38}" font-family="sans-serif" font-size="29" fill="#233128">${xml(line)}</text>`,
      )
      .join(
        "",
      )}<text x="48" y="${height - 35}" font-family="sans-serif" font-size="16" fill="#687562">Generated by a prompt chain · Full output in run details</text></svg>`,
  );
  const composite: OverlayOptions[] = [{ input: svg, top: 0, left: 0 }];
  if (image)
    composite.push({
      input: await sharp(image)
        .resize(1104, 570, { fit: "contain", background: "#e9e4d9" })
        .png()
        .toBuffer(),
      top: 160,
      left: 48,
    });
  return sharp({
    create: { width: 1200, height, channels: 4, background: "#f7f3e9" },
  })
    .composite(composite)
    .png()
    .toBuffer();
}
